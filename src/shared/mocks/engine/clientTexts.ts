/** Почему условия встречного предложения отличаются от запрошенных. */
export function explainCounter(
  requested: RequestedTerms,
  offer: LoanTerms,
  scenario: BorrowerScenario,
): string {
  const lessAmount = offer.amount < requested.amount;
  const longerTerm = offer.termMonths > requested.termMonths;

  const main =
    lessAmount && longerTerm
      ? 'Чтобы ежемесячный платёж был посильным для бизнеса, мы уменьшили сумму и увеличили срок.'
      : longerTerm
        ? 'Сумма та же, но срок дольше — так ежемесячный платёж будет меньше и комфортнее.'
        : lessAmount
          ? 'Сейчас можем выдать меньшую сумму, чтобы платёж не давил на бюджет бизнеса.'
          : 'Мы немного изменили условия, чтобы они лучше подходили вашему бизнесу.';

  const note = SCENARIO_NOTE[scenario];
  return note ? `${main} ${note}` : main;
}
