"""Кто такие ЛПР в малом бизнесе и на что каждый из них смотрит.

В малом бизнесе кредит почти никогда не берёт «абстрактный клиент». Анкету заполняет
один человек, деньги считает другой, документы готовит третий, а «да» говорит тот,
кто отвечает за кассу. Одну и ту же сумму они видят разными глазами:

- владелец/ИП — «когда деньги придут и что я смогу с ними сделать»;
- финансовый директор — «ставка, переплата, график, нагрузка на потоки»;
- главбух — «документы, назначения платежей, понятность для учёта»;
- наёмный управляющий — «что это закроет из операционки и не лишний ли риск для меня».

Этот файл — «знания о ролях»: словари, матрица приоров и каналы/время контакта.
Модель склонности (lpr_model.py) учится поверх этих знаний, а при её отсутствии
оркестратор опирается прямо на них (L1-fallback в lpr_offer.py).
"""
from __future__ import annotations

from dataclasses import dataclass, field


# ------------------------------- роли -------------------------------

@dataclass(frozen=True)
class LprRoleProfile:
    key: str                    # канонический код роли
    title: str                  # как говорим о роли в текстах и в консоли
    decision_lens: str          # чем человек меряет предложение (одна фраза)
    highlights: list[str] = field(default_factory=list)  # что подсвечивать в карточке
    channel: str = "лента кабинета"
    best_time: str = "в течение дня"


